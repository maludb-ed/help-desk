<?php
/** Proof — types, categories, tags (spec "Proof", 4–5): a cycle → 422; the tree's paths equal mcp_categories.path; a hidden category is hidden from a requester-only member as records_ro; tags delete untags N; a duplicate slug → 422; tag_by_slug_or_create. */
require __DIR__ . '/lib.php';
require dirname(__DIR__, 3) . '/app/features/statuses/queries.php';
require dirname(__DIR__, 3) . '/app/features/vocabulary/queries.php';
$owner = as_member(1); $lena = as_member(28);
$req = requester_of_member(26);

echo "1. Types\n";
$since = last_activity_id();
[$c, $b] = act($owner, '/settings/vocabulary/type.php', ['label' => 'SMOKE Change request', 'description' => 'SMOKE a planned change']);
$ty = (int) ($b['record_id'] ?? 0);
ok($c === 200 && $ty > 0 && (string) one('SELECT key FROM ticket_types WHERE id = :t', ['t' => $ty]) === 'smoke_change_request' && count(activity('type.save', $since)) === 1, 'type_save: created with a derived key, logged');
[$c, $b] = act($owner, '/settings/vocabulary/type.php', ['type' => type_id('incident'), 'label' => 'SMOKE Outage']);
ok($c === 200 && (string) one("SELECT label FROM ticket_types WHERE key = 'incident'") === 'SMOKE Outage', 'a built-in type is renamed');
act($owner, '/settings/vocabulary/type.php', ['type' => type_id('incident'), 'label' => 'Incident']);
[$c, $b] = act($owner, '/settings/vocabulary/type-archive.php', ['type' => type_id('task')]);
ok($c === 422 && msg($b) === 'A built-in type is renamed, never archived.', 'archiving a built-in: 422');
$t = mkticket($req, general_queue(), 'SMOKE a change'); q('UPDATE tickets SET type_id = :y WHERE id = :t', ['y' => $ty, 't' => $t]);
[$c, $b] = act($owner, '/settings/vocabulary/type-archive.php', ['type' => $ty]);
ok($c === 422 && str_contains(msg($b), '1 open ticket is a SMOKE Change request'), 'archiving a type with an open ticket: 422 naming it');
q("UPDATE tickets SET status_id = (SELECT id FROM ticket_statuses WHERE key = 'solved') WHERE id = :t", ['t' => $t]);
[$c, $b] = act($owner, '/settings/vocabulary/type-archive.php', ['type' => $ty]);
ok($c === 200 && one('SELECT archived_at FROM ticket_types WHERE id = :t', ['t' => $ty]) !== null, 'with the ticket solved: archived');

echo "2. Categories\n";
[$c, $b] = act($owner, '/settings/vocabulary/category.php', ['name' => 'SMOKE Billing', 'default_queue' => general_queue(), 'default_priority' => 'high']);
$bill = (int) $b['record_id'];
[$c, $b] = act($owner, '/settings/vocabulary/category.php', ['name' => 'SMOKE Refunds', 'parent' => $bill, 'default_type' => type_id('task'), 'requester_visible' => 'no']);
$ref = (int) $b['record_id'];
[$c, $b] = act($owner, '/settings/vocabulary/category.php', ['name' => 'SMOKE Chargebacks', 'parent' => $ref]);
$cb = (int) $b['record_id'];
ok($bill > 0 && $ref > 0 && $cb > 0, 'three levels created');
[$c, $d] = screen($owner, '/settings/vocabulary/?tab=categories');
$rows = array_values(array_filter($d['categories'], fn ($x) => in_array($x['category_id'], [$bill, $ref, $cb], true)));
ok(array_column($rows, 'depth') === [0, 1, 2] && $rows[2]['path'] === 'SMOKE Billing › SMOKE Refunds › SMOKE Chargebacks', 'the tree renders depth 0, 1, 2 and the path "SMOKE Billing › SMOKE Refunds › SMOKE Chargebacks"');
ok($rows[2]['path'] === (string) one('SELECT path FROM mcp_categories WHERE category_id = :c', ['c' => $cb]), 'equal to mcp_categories.path');
[$c, $b] = act($owner, '/settings/vocabulary/category.php', ['category' => $bill, 'parent' => $cb]);
ok($c === 422 && msg($b) === 'A category cannot sit under itself.', 'a cycle (Billing under Chargebacks): 422 "A category cannot sit under itself."');
[$c, $b] = act($owner, '/settings/vocabulary/category.php', ['category' => $bill, 'parent' => $bill]);
ok($c === 422, 'a category under itself: 422');
[$c, $b] = act($owner, '/settings/vocabulary/category.php', ['name' => 'SMOKE Refunds', 'parent' => $bill]);
ok($c === 422 && str_contains(msg($b), 'already sits there'), 'a sibling with the same name: 422');
$since = last_activity_id();
[$c, $b] = act($owner, '/settings/vocabulary/category.php', ['category' => $ref, 'default_priority' => 'urgent']);
ok($c === 200 && json_decode((string) activity('category.save', $since)[0]['after'], true) === ['default_priority' => 'urgent'] && (int) one('SELECT parent_id FROM categories WHERE id = :c', ['c' => $ref]) === $bill, 'one default changed: logged alone, the parent kept');
$ro = ro_pdo(26);
$seen = array_map('intval', $ro->query('SELECT category_id FROM mcp_categories')->fetchAll(PDO::FETCH_COLUMN));
ok(in_array($bill, $seen, true) && !in_array($ref, $seen, true), 'as records_ro for Priya (requester only): Billing visible, the hidden Refunds not');
$seen = array_map('intval', ro_pdo(27)->query('SELECT category_id FROM mcp_categories')->fetchAll(PDO::FETCH_COLUMN));
ok(in_array($ref, $seen, true), 'for Marco (tickets.view_queue): Refunds visible');
$body = page($owner, '/settings/vocabulary/?tab=categories')['body'];
ok(str_contains($body, 'id="category-row-' . $cb . '"') && str_contains($body, '→ General') && str_contains($body, 'id="category-row-' . $bill . '-add-child-btn"'), 'the screen: the rows, the routing chip "→ General", Add child');
$tc = mkticket($req, general_queue(), 'SMOKE categorised'); q('UPDATE tickets SET category_id = :c WHERE id = :t', ['c' => $cb, 't' => $tc]);
[$c, $b] = act($owner, '/settings/vocabulary/category-archive.php', ['category' => $ref]);
ok($c === 200 && ($b['archived_ids'] ?? []) == [$ref, $cb] && one('SELECT archived_at FROM categories WHERE id = :c', ['c' => $cb]) !== null, 'archiving Refunds takes Chargebacks with it');
ok((int) one('SELECT category_id FROM tickets WHERE id = :t', ['t' => $tc]) === $cb && (string) one('SELECT category_name FROM mcp_tickets WHERE ticket_id = :t', ['t' => $tc]) === 'SMOKE Chargebacks', 'the ticket keeps its category_id and the view still names it');
[$c, $b] = act($owner, '/settings/vocabulary/category.php', ['name' => 'SMOKE Under archived', 'parent' => $ref]);
ok($c === 422 && msg($b) === 'That parent category is archived.', 'a new category under an archived one: 422');
[$c, $d] = screen($owner, '/settings/vocabulary/?tab=categories');
ok(count(array_filter($d['categories'], fn ($x) => $x['category_id'] === $cb)) === 0, 'the archived branch is off the tree');

echo "3. Tags\n";
$since = last_activity_id();
[$c, $b] = act($lena, '/settings/vocabulary/tag.php', ['label' => 'SMOKE VIP customer']);
$tag = (int) ($b['record_id'] ?? 0);
ok($c === 200 && $tag > 0 && (string) one('SELECT slug FROM tags WHERE id = :t', ['t' => $tag]) === 'smoke-vip-customer' && count(activity('tag.save', $since)) === 1, 'a lead adds a tag (tag_save, tickets.manage): slug derived, logged');
[$c, $b] = act($lena, '/settings/vocabulary/tag.php', ['label' => 'SMOKE Other', 'slug' => 'smoke-vip-customer']);
ok($c === 422 && str_contains(msg($b), 'already SMOKE VIP customer'), 'a duplicate slug: 422');
[$c, $b] = act($lena, '/settings/vocabulary/tag.php', ['tag' => $tag, 'label' => 'SMOKE VIP', 'slug' => 'smoke-vip']);
ok($c === 200 && q('SELECT slug, label FROM tags WHERE id = :t', ['t' => $tag])[0] === ['slug' => 'smoke-vip', 'label' => 'SMOKE VIP'], 'rename with a new slug');
[$c, $b] = act($lena, '/settings/vocabulary/tag.php', ['label' => 'SMOKE Bad', 'slug' => 'Not a slug!']);
ok($c === 422, 'a malformed slug: 422');
$pdo = pdo();
$a = tag_by_slug_or_create($pdo, 'Hard Ware');
ok((string) one('SELECT slug FROM tags WHERE id = :t', ['t' => $a]) === 'hard-ware' && (string) one('SELECT label FROM tags WHERE id = :t', ['t' => $a]) === 'Hard Ware', 'tag_by_slug_or_create("Hard Ware") → slug hard-ware');
ok(tag_by_slug_or_create($pdo, 'hard-ware') === $a && tag_by_slug_or_create($pdo, 'HARD WARE') === $a, 'reused on the second call, by slug or by label');
$ta = mkticket($req, general_queue(), 'SMOKE tagged a'); $tb = mkticket($req, general_queue(), 'SMOKE tagged b');
q('INSERT INTO ticket_tags (ticket_id, tag_id) VALUES (:a, :t), (:b, :t2)', ['a' => $ta, 't' => $tag, 'b' => $tb, 't2' => $tag]);
[$c, $d] = screen($owner, '/settings/vocabulary/?tab=tags&q=vip');
ok(count($d['tags']) === 1 && $d['tags'][0]['usage'] === 2, 'the chip counts 2 uses; the search narrows');
[$c, $b] = act($lena, '/settings/vocabulary/tag-delete.php', ['tag' => $tag]);
ok($c === 403, 'a lead may not delete a tag (settings.manage): 403');
$since = last_activity_id();
[$c, $b] = act($owner, '/settings/vocabulary/tag-delete.php', ['tag' => $tag]);
ok($c === 200 && ($b['tickets_untagged'] ?? -1) === 2 && (int) one('SELECT count(*) FROM ticket_tags WHERE tag_id = :t', ['t' => $tag]) === 0 && one('SELECT 1 FROM tags WHERE id = :t', ['t' => $tag]) === false, 'delete untags 2 tickets and returns 2');
ok(str_contains((string) activity('tag.delete', $since)[0]['after'], '"tickets_untagged": 2'), 'tag.delete logged with tickets_untagged');
finish();
