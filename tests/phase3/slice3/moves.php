<?php
/** Proof — every move the table allows, and none it does not (spec "Proof", 3): the triage shortcuts, the refusals in words, the lead's early close, the requester's confirm and reopen inside and outside the window. */
require __DIR__ . '/lib.php';
$W = world();
$marco = as_member(27); $lena = as_member(28); $priya = as_member(26); $owner = as_member(1);
act($owner, '/settings/queues/member.php', ['queue' => general_queue(), 'member' => 27]);
$new = fn (string $subject = 'SMOKE a move') => (int) act($marco, '/tickets/save.php', ['subject' => $subject, 'body' => 'x', 'queue' => $W['it']])[1]['record_id'];
$tr = fn (int $t, int $since) => array_map(fn ($r) => json_decode((string) $r['before'], true) + ['after' => json_decode((string) $r['after'], true)], array_filter(activity('ticket.transition', $since), fn ($r) => (int) $r['ticket_id'] === $t));

echo "1. From new: Accept, Decline, Snooze\n";
$t = $new('SMOKE accept me');
$since = last_activity_id();
[$c, $b] = act($marco, '/tickets/transition.php', ['ticket' => $t, 'status' => 'open', 'assignee' => 'me']);
$row = ticket_row($t);
ok($c === 200 && ticket_status($t) === 'open' && (int) $row['assignee_member_id'] === 27, 'Accept: open and assigned to Marco');
$rows = $tr($t, $since);
ok(count($rows) === 1 && $rows[0]['status'] === 'new' && $rows[0]['after']['status'] === 'open' && $rows[0]['after']['via'] === 'triage', 'ticket.transition: before new, after open, via triage');
ok(count(array_filter(activity('ticket.assign', $since), fn ($r) => (int) $r['ticket_id'] === $t)) === 1, 'and a ticket.assign row');
$t = $new('SMOKE decline me');
[$c, $b] = act($marco, '/tickets/transition.php', ['ticket' => $t, 'status' => 'solved', 'resolution_code' => 'no_action']);
ok($c === 422 && str_contains(msg($b), 'Say why in a note'), 'Decline without a note: 422');
[$c, $b] = act($marco, '/tickets/transition.php', ['ticket' => $t, 'status' => 'solved', 'resolution_code' => 'no_action', 'note' => 'SMOKE not ours']);
ok($c === 200 && ticket_status($t) === 'solved' && ticket_row($t)['resolution_code'] === 'no_action' && (int) one("SELECT count(*) FROM messages WHERE ticket_id = :t AND kind = 'internal_note'", ['t' => $t]) === 1, 'Decline with a note: solved no_action, the note added');
ok(ticket_row($t)['solved_at'] !== null && targets($t)['resolution']['met_at'] !== null, 'solved_at stamped and the resolution target met (the trigger)');
$t = $new('SMOKE snooze me');
$until = (new DateTimeImmutable('tomorrow 09:00'))->format('Y-m-d\TH:i');
[$c, $b] = act($marco, '/tickets/transition.php', ['ticket' => $t, 'status' => 'pending', 'pending_until' => $until]);
ok($c === 200 && ticket_status($t) === 'pending' && ticket_row($t)['pending_until'] !== null && targets($t)['first_response']['paused_at'] !== null, 'Snooze: pending with pending_until; the clock paused');

echo "2. What the table refuses\n";
$t = $new('SMOKE refuse me');
act($marco, '/tickets/transition.php', ['ticket' => $t, 'status' => 'open']);
[$c, $b] = act($marco, '/tickets/transition.php', ['ticket' => $t, 'status' => 'solved']);
ok($c === 422 && msg($b) === 'Solving needs a resolution code.', 'open → solved without a code: 422 "Solving needs a resolution code."');
[$c, $b] = act($marco, '/tickets/transition.php', ['ticket' => $t, 'status' => 'on_hold']);
ok($c === 422 && msg($b) === 'Putting a ticket on hold needs a reason.', 'open → on hold without a reason: 422');
[$c, $b] = act($marco, '/tickets/transition.php', ['ticket' => $t, 'status' => 'on_hold', 'hold_reason' => 'awaiting_third_party']);
ok($c === 200 && ticket_status($t) === 'on_hold' && ticket_row($t)['hold_reason'] === 'awaiting_third_party', 'with a reason: on hold');
[$c, $b] = act($marco, '/tickets/transition.php', ['ticket' => $t, 'status' => 'open']);
ok($c === 200 && ticket_row($t)['hold_reason'] === null, 'Resume: open, the reason cleared by the trigger');
[$c, $b] = act($marco, '/tickets/transition.php', ['ticket' => $t, 'status' => 'closed', 'resolution_code' => 'resolved']);
ok($c === 422 && msg($b) === 'Closing early needs the Lead role.', 'open → closed as support: 422 "Closing early needs the Lead role."');
[$c, $b] = act($marco, '/tickets/close.php', ['ticket' => $t, 'resolution_code' => 'resolved']);
ok($c === 403, 'ticket_close as support: 403 (tickets.manage)');
[$c, $b] = act($lena, '/tickets/close.php', ['ticket' => $t, 'resolution_code' => 'workaround']);
ok($c === 200 && ticket_status($t) === 'closed' && ticket_row($t)['resolution_code'] === 'workaround' && ticket_row($t)['closed_at'] !== null, 'as Lena, with a code: closed');
ok(count(array_filter(activity('ticket.close', 0), fn ($r) => (int) $r['ticket_id'] === $t)) === 1, 'ticket.close logged');
[$c, $b] = act($lena, '/tickets/transition.php', ['ticket' => $t, 'status' => 'open']);
ok($c === 422 && str_contains(msg($b), 'cannot move from Closed.'), 'closed → anything: 422 "… cannot move from Closed."');
[$c, $b] = act($lena, '/tickets/reopen.php', ['ticket' => $t]);
ok($c === 422 && str_contains(msg($b), 'cannot move from Closed'), 'ticket_reopen on a closed ticket: 422');
ok(one('SELECT expires_at FROM ticket_links_secure WHERE ticket_id = :t AND rotated_at IS NULL', ['t' => $t]) !== null, 'the secure link got its expiry at close (the trigger)');
$t = $new('SMOKE reopen me');
act($marco, '/tickets/transition.php', ['ticket' => $t, 'status' => 'open']);
act($marco, '/tickets/transition.php', ['ticket' => $t, 'status' => 'solved', 'resolution_code' => 'resolved']);
[$c, $b] = act($marco, '/tickets/reopen.php', ['ticket' => $t]);
ok($c === 200 && ticket_status($t) === 'open' && (int) ticket_row($t)['reopen_count'] === 1 && ticket_row($t)['solved_at'] === null && ticket_row($t)['first_reopened_at'] !== null, 'solved → open by support: reopen_count 1, solved_at cleared, first_reopened_at set');
ok(targets($t)['resolution']['met_at'] === null, 'the resolution clock restarted');
[$c, $b] = act($marco, '/tickets/transition.php', ['ticket' => $t, 'status' => 'open']);
ok($c === 422 && str_contains(msg($b), 'is already Open'), 'the same status again: 422');

echo "3. The requester's own moves\n";
$tp = (int) act($priya, '/tickets/save.php', ['subject' => 'SMOKE Priya confirms', 'body' => 'x'])[1]['record_id'];
q('UPDATE tickets SET queue_id = :q WHERE id = :t', ['q' => $W['it'], 't' => $tp]);
act($marco, '/tickets/reply.php', ['ticket' => $tp, 'body' => 'Done, please check.', 'then_status' => 'pending']);
ok(ticket_status($tp) === 'pending', 'support replied and set it pending');
$since = last_activity_id();
[$c, $b] = act($priya, '/tickets/confirm.php', ['ticket' => $tp]);
ok($c === 200 && ticket_status($tp) === 'solved' && ticket_row($tp)['resolution_code'] === 'resolved', 'Priya confirms: solved resolved');
$rows = $tr($tp, $since);
ok(count($rows) === 1 && $rows[0]['after']['via'] === 'requester' && count(activity('ticket.confirm', $since)) === 1, 'via requester; ticket.confirm logged');
[$c, $b] = act($priya, '/tickets/reopen.php', ['ticket' => $tp, 'note' => 'Still broken.']);
ok($c === 200 && ticket_status($tp) === 'open' && (int) one("SELECT count(*) FROM messages WHERE ticket_id = :t AND kind = 'public_reply' AND author_member_id = 26", ['t' => $tp]) === 2, 'her Reopen inside the window: open, her note a public reply');
act($marco, '/tickets/transition.php', ['ticket' => $tp, 'status' => 'solved', 'resolution_code' => 'resolved']);
q("UPDATE tickets SET solved_at = now() - interval '20 days' WHERE id = :t", ['t' => $tp]);
[$c, $b] = act($priya, '/tickets/reopen.php', ['ticket' => $tp]);
ok($c === 422 && msg($b) === 'This request was solved more than 14 days ago — file a new one and mention ' . ticket_row($tp)['number'] . '.', 'outside the window: the 14-day sentence');
[$c, $b] = act($marco, '/tickets/reopen.php', ['ticket' => $tp]);
ok($c === 200 && ticket_status($tp) === 'open', 'support reopens regardless of the window');
[$c, $b] = act($priya, '/tickets/transition.php', ['ticket' => $tp, 'status' => 'solved', 'resolution_code' => 'resolved']);
ok($c === 403, 'a requester has no ticket_transition: 403');
[$c, $b] = act($marco, '/tickets/confirm.php', ['ticket' => $tp]);
ok($c === 403, 'support cannot confirm for the requester: 403');
echo "4. The matrix drives it\n";
act($owner, '/settings/statuses/transition.php', ['from_category' => 'open', 'to_category' => 'pending', 'allowed' => 'no']);
[$c, $b] = act($marco, '/tickets/transition.php', ['ticket' => $tp, 'status' => 'pending']);
ok($c === 422 && str_contains(msg($b), 'cannot move from Open to Pending here'), 'with open → pending removed from the matrix, the move is refused in words');
act($owner, '/settings/statuses/transition.php', ['from_category' => 'open', 'to_category' => 'pending', 'allowed' => 'yes', 'may_carry' => ['pending_until'], 'label' => 'Wait for the requester']);
[$c, $b] = act($marco, '/tickets/transition.php', ['ticket' => $tp, 'status' => 'pending']);
ok($c === 200, 'and allowed again once restored');
finish();
