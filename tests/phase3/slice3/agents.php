<?php
/** Proof — assigning to an agent (spec "Proof", 5): the dispatch row via chat answered by the stubbed kernel; the stub failing leaves the assignment; under a run token via duty and no call; ticket_dispatch repeats it; mcp_agent_dispatches readable by the queue's holders. */
require __DIR__ . '/lib.php';
$W = world();
$marco = as_member(27); $owner = as_member(1); $priya = as_member(26);
$t = $W['t_jo2'];
echo "1. Assign to Frontline (agent 40, in IT through the department)\n";
$since = last_activity_id();
[$c, $b] = act($marco, '/tickets/assign.php', ['ticket' => $t, 'assignee' => 40]);
ok($c === 200 && ($b['dispatch']['status'] ?? '') === 'answered' && ($b['dispatch']['via'] ?? '') === 'chat', 'ticket_assign: 200, dispatched via chat, answered');
$d = dispatches($t);
ok(count($d) === 1 && (int) $d[0]['agent_member_id'] === 40 && (int) $d[0]['acting_member_id'] === 27 && $d[0]['status'] === 'answered' && (int) $d[0]['run_id'] === 1 && str_contains((string) $d[0]['reply_excerpt'], 'fake expert'), 'the row: agent 40, acting Marco, answered with a run id and an excerpt');
ok(count(array_filter(activity('ticket.dispatch', $since), fn ($r) => (int) $r['ticket_id'] === $t)) === 1 && count(array_filter(activity('ticket.assign', $since), fn ($r) => (int) $r['ticket_id'] === $t)) === 1, 'ticket.assign and ticket.dispatch logged');
$a = json_decode((string) array_values(array_filter(activity('ticket.assign', $since), fn ($r) => (int) $r['ticket_id'] === $t))[0]['after'], true);
ok($a['assignee_kind'] === 'agent' && $a['assignee_name'] === 'SMOKE Frontline' && $a['via'] === 'manual', 'the assign row carries the name and kind');
ok(count(outbox($t, 'assigned')) === 0, 'no assigned email to an agent (it is dispatched)');
$s = kernel_state();
ok(($s['chat_status'] ?? null) === null, 'the fake kernel is in its normal state');
echo "2. The kernel down: the assignment stands, the dispatch fails\n";
kernel_state(function ($s) { $s['chat_status'] = 500; $s['chat_message'] = 'The runner is down.'; return $s; });
$t2 = $W['t_jo'];
[$c, $b] = act($marco, '/tickets/assign.php', ['ticket' => $t2, 'assignee' => 40]);
ok($c === 200 && (int) ticket_row($t2)['assignee_member_id'] === 40 && ($b['dispatch']['status'] ?? '') === 'failed', 'assigned (200) and the dispatch failed');
$d = dispatches($t2);
ok(end($d)['status'] === 'failed' && str_contains((string) end($d)['detail'], 'runner is down'), 'the row says failed with the kernel\'s sentence');
kernel_state(function ($s) { unset($s['chat_status'], $s['chat_message']); return $s; });
echo "3. ticket_dispatch repeats the call\n";
[$c, $b] = act($marco, '/tickets/dispatch.php', ['ticket' => $t2]);
ok($c === 200 && ($b['dispatch']['status'] ?? '') === 'answered' && count(dispatches($t2)) === 2, 'repeated by hand: a second row, answered');
[$c, $b] = act($marco, '/tickets/dispatch.php', ['ticket' => $W['t_fac']]);
ok($c === 404, 'a ticket Marco cannot see: 404');
act($marco, '/tickets/assign.php', ['ticket' => $t, 'assignee' => 'me']);
[$c, $b] = act($marco, '/tickets/dispatch.php', ['ticket' => $t]);
ok($c === 422 && msg($b) === ticket_row($t)['number'] . ' is not assigned to an agent.', 'a ticket assigned to a person: 422 "… is not assigned to an agent."');
echo "4. Under a run token: via duty, no call\n";
kernel_state(function ($s) { $s['facts']['302'] = ['valid' => true, 'is_agent' => true, 'member_id' => 40, 'run_id' => 302, 'request_id' => 'req-run-302', 'trigger' => 'duty', 'endpoints' => [['name' => 'Records MCP']]]; return $s; });
[$tok, $relay] = run_token(40, 302);
$before = count(dispatches($t));
[$c, $b] = act_token('/tickets/assign.php', ['ticket' => $t, 'assignee' => 40], ['X-Action-Token: ' . $tok, 'X-Action-Relay: ' . $relay]);
$d = dispatches($t);
ok($c === 200 && count($d) === $before + 1 && end($d)['via'] === 'duty' && end($d)['acting_member_id'] === null && end($d)['run_id'] === null, 'the agent assigns itself: a row via duty, nobody acting, no run (no call)');
kernel_state(function ($s) { unset($s['facts']); return $s; });
echo "5. Who reads the dispatches\n";
$ro = ro_pdo(27);
ok((int) $ro->query('SELECT count(*) FROM mcp_agent_dispatches WHERE ticket_id = ' . $t)->fetchColumn() >= 2, 'Marco (IT) reads them through mcp_agent_dispatches');
ok((int) ro_pdo(26)->query('SELECT count(*) FROM mcp_agent_dispatches WHERE ticket_id = ' . $t)->fetchColumn() === 0, 'Priya reads none');
[$c, $b] = act($marco, '/tickets/assign.php', ['ticket' => $t, 'assignee' => 29]);
ok($c === 422 && msg($b) === 'SMOKE Colin is not in the SMOKE IT help queue.', 'an assignee outside the queue: 422 "… is not in the … queue."');
[$c, $b] = act($marco, '/tickets/assign.php', ['ticket' => $t, 'queue' => $W['fac']]);
ok($c === 403, 'moving a ticket into a queue Marco does not work: 403');
[$c, $b] = act($owner, '/tickets/assign.php', ['ticket' => $t, 'queue' => $W['fac'], 'assignee' => 29]);
ok($c === 200 && (int) ticket_row($t)['queue_id'] === $W['fac'] && (int) ticket_row($t)['assignee_member_id'] === 29, 'the admin moves it to Facilities and gives it to Colin');
ok(count(outbox($t, 'assigned')) === 1 && (int) outbox($t, 'assigned')[0]['member_id'] === 29, 'Colin is told');
act($owner, '/tickets/assign.php', ['ticket' => $t, 'queue' => $W['it'], 'assignee' => 'none']);
finish();
