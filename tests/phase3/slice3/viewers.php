<?php
/** Proof — viewers and the timeline (spec "Proof", 9–10): two sessions see each other, "is replying", gone after two minutes, no activity row; the timeline in words, internals only for the queue. */
require __DIR__ . '/lib.php';
$W = world();
$marco = as_member(27); $lena = as_member(28); $priya = as_member(26);
$t = $W['t_jo'];
echo "1. Viewers\n";
$since = last_activity_id();
$tok = csrf_of(page($marco, '/')['body']);
$r = req('POST', '/tickets/viewing.php', ['jar' => $marco, 'form' => ['ticket' => $t, 'composing' => 'no', 'csrf_token' => $tok]]);
ok($r['code'] === 204, 'viewing.php answers 204');
$tokL = csrf_of(page($lena, '/')['body']);
req('POST', '/tickets/viewing.php', ['jar' => $lena, 'form' => ['ticket' => $t, 'composing' => 'yes', 'csrf_token' => $tokL]]);
[$c, $d] = screen($marco, '/tickets/' . $t);
$v = $d['ticket']['viewers'] ?? [];
ok(count($v) === 1 && $v[0]['member_id'] === 28 && $v[0]['composing'] === true, 'Marco sees Lena, replying');
[$c, $d] = screen($lena, '/tickets/' . $t);
ok(count(array_filter($d['ticket']['viewers'], fn ($x) => $x['member_id'] === 27)) === 1, 'Lena sees Marco');
ok(str_contains(page($marco, '/tickets/' . $t)['body'], 'SMOKE Lena is replying'), 'the page says "SMOKE Lena is replying"');
q("UPDATE ticket_viewers SET last_seen_at = now() - interval '3 minutes' WHERE member_id = 28");
[$c, $d] = screen($marco, '/tickets/' . $t);
ok(count($d['ticket']['viewers']) === 0, 'after two minutes idle the chip is gone');
ok(activity('screen.view', $since) !== [] && count(array_filter(q('SELECT action FROM activity_log WHERE id > :s', ['s' => $since]), fn ($r) => str_contains($r['action'], 'view') && $r['action'] !== 'screen.view')) === 0, 'no activity row from viewing.php (only the pages\' screen.view)');
$r = req('POST', '/tickets/viewing.php', ['jar' => $priya, 'form' => ['ticket' => $t, 'csrf_token' => csrf_of(page($priya, '/')['body'])]]);
ok($r['code'] === 404, 'a ticket Priya cannot see: 404');
echo "2. The timeline\n";
[$c, $d] = screen($marco, '/tickets/' . $t);
$words = array_map(fn ($h) => $h['words'], $d['history']);
$has = fn (string $s) => count(array_filter($words, fn ($w) => str_contains($w, $s))) > 0;
ok($has('replied') && $has('Status') && $has('assigned it to SMOKE Frontline (agent)') && $has('Dispatched to SMOKE Frontline'), 'the queue holder\'s timeline: the reply, the moves, the assignment to the agent, the dispatch');
ok($has('(agent)') === true, 'the agent is marked');
$tp = $W['t_p1'];
[$c, $d] = screen($priya, '/tickets/' . $tp);
$words = array_map(fn ($h) => $h['words'], $d['history']);
ok(count(array_filter($words, fn ($w) => str_contains($w, 'note') || str_contains($w, 'Dispatched') || str_contains($w, 'logged') || str_contains($w, 'SLA'))) === 0 && count($words) > 0, 'the requester\'s timeline holds no note, no dispatch, no time, no SLA row (' . count($words) . ' rows)');
$body = page($priya, '/tickets/' . $tp)['body'];
ok(str_contains($body, 'id="ticket-timeline"') && !str_contains($body, 'added a note'), 'the page agrees');
echo "3. The dashboard and my-tickets\n";
[$c, $d] = screen($marco, '/');
ok($c === 200 && count($d['needs_me']) > 0 && isset($d['needs_me'][0]['reason']), 'Marco\'s "What needs me" lists tickets with a reason');
[$c, $d] = screen($priya, '/');
ok($c === 200 && count($d['my_tickets']) > 0 && $d['needs_me'] === [], 'Priya\'s home: her tickets, nothing to work');
[$c, $d] = screen($priya, '/my-tickets?state=waiting');
ok($c === 200 && count(array_filter($d['tickets'], fn ($x) => !in_array($x['status']['category'], ['pending', 'solved'], true))) === 0, '"Waiting on me": pending and solved only');
finish();
