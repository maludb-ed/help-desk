<?php
/** Proof — the poll (spec "Proof", 4): with no webhook, the worker's step picks the unseen message within one pass and advances last_uid; a message the stub refuses to read leaves the row failed and the floor below it while the others still go; inbound_retry then processes it; Poll now from the screen; ignore. */
require __DIR__ . '/lib.php';
$W = world();
$owner = as_member(1);
ensure_mailbox();
echo "1. The poll\n";
put_mail(40, ['from' => 'Polled <polled@customer.invalid>', 'subject' => 'Missed by the webhook'], 'Nobody called the webhook.');
$n = poll_now();
$row = inbound_row(40);
ok($n >= 1 && $row !== null && $row['status'] === 'processed' && $row['ticket_id'] !== null, 'the poll handled the unseen message (' . $n . ')');
$mb = find_mailbox(pdo(), mailbox_id());
ok((int) $mb['last_uid'] === 40 && $mb['last_polled_at'] !== null, 'last_uid advanced to 40, last_polled_at stamped (' . $mb['last_uid'] . ')');
ok(in_array('\\Seen', mail_flags(40), true), 'marked seen');
$src = q("SELECT source FROM activity_log WHERE action = 'mail.inbound' ORDER BY id DESC LIMIT 1")[0]['source'];
ok($src === 'cron', 'the row logged with source cron (the worker)');
ok(poll_now() === 0, 'a second pass handles nothing');
echo "2. A message the stub refuses\n";
put_mail(41, ['from' => 'Locked <locked@customer.invalid>', 'subject' => 'Locked'], 'x', ['refuse_read' => true]);
put_mail(42, ['from' => 'After <after@customer.invalid>', 'subject' => 'After the locked one'], 'y');
$n = poll_now();
$row = inbound_row(41);
ok($n === 1 && $row !== null && $row['status'] === 'failed' && str_contains((string) $row['error'], 'locked'), 'the refused message: the row failed with the error; the one after it still handled (' . $n . ')');
ok(inbound_row(42)['status'] === 'processed' && (int) find_mailbox(pdo(), mailbox_id())['last_uid'] === 40, 'the floor stays below the failure (last_uid 40) so the next poll sees it again');
$body = page($owner, '/settings/mailboxes/inbound')['body'];
ok(str_contains($body, 'id="inbound-row-' . $row['id'] . '-retry"') && str_contains($body, 'Failed'), 'the inbound screen lists it with Retry');
$body = page($owner, '/settings/mailboxes/')['body'];
ok(str_contains($body, 'id="mailbox-card-' . mailbox_id() . '-failures"'), 'the mailbox card shows the problem count');
malumail_state(function ($s) { unset($s['mailboxes'][MAILBOX_ADDRESS]['41']['refuse_read']); return $s; });
$since = last_activity_id();
[$c, $b] = act($owner, '/settings/mailboxes/inbound/retry.php', ['inbound' => (int) $row['id']]);
ok($c === 200 && inbound_row(41)['status'] === 'processed' && inbound_row(41)['ticket_id'] !== null && count(activity('mail.inbound_retry', $since)) === 1, 'inbound_retry processes it');
ok(in_array('\\Seen', mail_flags(41), true) && in_array('\\Seen', mail_flags(42), true), 'both marked seen');
[$c, $b] = act($owner, '/settings/mailboxes/inbound/retry.php', ['inbound' => (int) $row['id']]);
ok($c === 422, 'retrying a processed one: 422');
put_mail(43, ['from' => 'Later <later@customer.invalid>', 'subject' => 'Polled from the screen'], 'z');
$since = last_activity_id();
[$c, $b] = act($owner, '/settings/mailboxes/poll.php', ['mailbox' => mailbox_id()]);
ok($c === 200 && ($b['handled'] ?? 0) === 1 && inbound_row(43)['status'] === 'processed' && (int) find_mailbox(pdo(), mailbox_id())['last_uid'] === 43 && count(activity('mailbox.poll', $since)) === 1, 'Poll now from the screen handles the new one; last_uid 43');
echo "3. Ignore\n";
put_mail(44, ['from' => 'Locked2 <locked2@customer.invalid>', 'subject' => 'Locked again'], 'x', ['refuse_read' => true]);
poll_now();
$r44 = inbound_row(44);
ok($r44 !== null && $r44['status'] === 'failed', 'another refused one: failed');
[$c, $b] = act($owner, '/settings/mailboxes/inbound/ignore.php', ['inbound' => (int) $r44['id'], 'reason' => 'SMOKE junk']);
ok($c === 200 && inbound_row(44)['status'] === 'ignored' && inbound_row(44)['error'] === 'SMOKE junk', 'inbound_ignore: ignored with the reason');
malumail_state(function ($s) { unset($s['mailboxes'][MAILBOX_ADDRESS]['44']['refuse_read']); $s['mailboxes'][MAILBOX_ADDRESS]['44']['flags'] = ['\\Seen']; return $s; });
[$c, $d] = screen($owner, '/settings/mailboxes/inbound?status=ignored');
ok(count(array_filter($d['inbound'], fn ($x) => $x['status'] !== 'ignored')) === 0 && count($d['inbound']) >= 1, 'the inbound list filters by status');
ok(poll_now() === 0, 'an ignored message is not read again');
finish();
