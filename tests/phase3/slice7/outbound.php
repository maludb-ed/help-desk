<?php
/** Proof — outbound and K6 (spec "Proof", 5): a reply queues the requester's email with the [number] subject, in_reply_to, the marker, the secure link, the reply in full and no note; the stub receives it; texts through the stubbed kernel: sent, every refusal a skip with the email still sent, a 5xx retried and the 5th failed; no API key → queued and unconfigured; the dedupe key; an inactive member and an eval run queue nothing. */
require __DIR__ . '/lib.php';
$W = world();
$marco = as_member(27); $lena = as_member(28); $owner = as_member(1);
ensure_mailbox();
echo "1. A reply to an external\n";
put_mail(50, ['from' => 'Outbound <outbound@customer.invalid>', 'subject' => 'Need a cable'], 'Please send a cable.');
webhook(50);
$t = (int) inbound_row(50)['ticket_id'];
send_batch();                                                                                        // the created notice goes out first
act($marco, '/tickets/note.php', ['ticket' => $t, 'body' => 'SECRETNOTE customer is grumpy']);
$since = last_activity_id();
[$c, $b] = act($marco, '/tickets/reply.php', ['ticket' => $t, 'body' => "A cable is on its way.\nRegards"]);
$rows = outbox_rows($t, 'email');
$mine = array_values(array_filter($rows, fn ($o) => $o['kind'] === 'replied' && $o['requester_id'] !== null));
ok(count($mine) === 1 && $mine[0]['status'] === 'queued' && count(array_filter($rows, fn ($o) => (int) $o['member_id'] === 27)) === 0, 'one replied row for the requester, none for Marco');
$before = count(malumail_sent());
$r = send_batch();
$sent = array_slice(malumail_sent(), $before);
$mail = end($sent);
$num = ticket_row($t)['number'];
ok(count($sent) === 1 && $mail['to'] === 'outbound@customer.invalid' && str_starts_with($mail['subject'], '[' . $num . ']') && $mail['from'] === MAILBOX_ADDRESS && $mail['from_name'] === 'SMOKE Support', 'the stub received it: to the requester, [' . $num . '] in the subject, from the queue mailbox');
ok(($mail['in_reply_to'] ?? '') === '<mail-50@customer.invalid>' && in_array('<mail-50@customer.invalid>', $mail['references'] ?? [], true), 'threaded on the inbound Message-ID');
ok(str_contains($mail['text'], MAIL_MARKER) && str_contains($mail['text'], "A cable is on its way.\nRegards") && preg_match('#/t/[a-f0-9]{48}#', $mail['text']) === 1 && str_contains($mail['text'], 'The IT desk'), 'the marker, the reply in full, the secure link, the signature');
ok(!str_contains($mail['text'], 'SECRETNOTE') && !str_contains($mail['html'], 'SECRETNOTE'), 'and no note');
$row = outbox_rows($t, 'email'); $last = end($row);
ok($last['status'] === 'sent' && preg_match('/^<mm-\d+@fake\.malumail>$/', (string) $last['detail']) === 1 && (int) one("SELECT count(*) FROM outbound_email WHERE ticket_id = :t AND status = 'sent'", ['t' => $t]) >= 2, 'the row is sent with the provider\'s Message-ID; outbound_email rows');
ok(count(activity('notification.send', $since)) >= 1 && json_decode(activity('notification.send', $since)[0]['after'], true)['outcome'] === 'sent' && !str_contains(json_encode(activity('notification.send', $since)), 'outbound@'), 'notification.send logged: outcome, no address');
ok((string) one('SELECT email_message_id FROM messages WHERE id = :m', ['m' => (int) $last['message_ref_id']]) === $last['detail'], 'the message carries the Message-ID it went out with');
echo "2. Texts through the kernel\n";
act($lena, '/settings/prefs.php', ['email_enabled' => 'yes', 'text_enabled' => 'yes', 'kinds' => ['assigned', 'replied'], 'text_kinds' => ['assigned']]);
$mk = fn (string $s) => (int) act($marco, '/tickets/save.php', ['subject' => $s, 'body' => 'x', 'queue' => $W['it']])[1]['record_id'];
sms_mode('ok');
$t1 = $mk('SMOKE text ok');
act($marco, '/tickets/assign.php', ['ticket' => $t1, 'assignee' => 28]);
$rows = outbox_rows($t1);
ok(count(array_filter($rows, fn ($o) => $o['channel'] === 'text' && (int) $o['member_id'] === 28)) === 1 && count(array_filter($rows, fn ($o) => $o['channel'] === 'email' && (int) $o['member_id'] === 28)) === 1, 'assigning to Lena queues a text row and an email row');
send_batch();
$rows = outbox_rows($t1);
$text = array_values(array_filter($rows, fn ($o) => $o['channel'] === 'text'))[0]; $email = array_values(array_filter($rows, fn ($o) => $o['channel'] === 'email'))[0];
ok($text['status'] === 'sent' && str_starts_with((string) $text['detail'], 'kernel:') && $email['status'] === 'sent', 'the kernel answered 202: the text is sent (the kernel\'s id kept) and the email is sent');
$smsLog = array_values(array_filter(array_map(fn ($l) => json_decode($l, true), explode("\n", (string) @file_get_contents(need('FAKE_KERNEL_STATE') . '.sms')))));
$lastSms = end($smsLog);
ok((int) $lastSms['member_id'] === 28 && mb_strlen($lastSms['text']) <= 480 && str_contains($lastSms['text'], ticket_row($t1)['number']) && str_contains($lastSms['text'], '/tickets/' . $t1) && ($lastSms['reference'] ?? '') === 'ticket:' . $t1, 'the text names the number and the link, nobody else, with the reference');
$codes = [];
foreach (['no_verified_phone', 'opted_out', 'rate_limited', 'not_held', 'no_sender'] as $mode) {
    sms_mode($mode);
    $tx = $mk('SMOKE text ' . $mode);
    act($marco, '/tickets/assign.php', ['ticket' => $tx, 'assignee' => 28]);
    send_batch();
    $rows = outbox_rows($tx);
    $tr = array_values(array_filter($rows, fn ($o) => $o['channel'] === 'text'))[0]; $er = array_values(array_filter($rows, fn ($o) => $o['channel'] === 'email'))[0];
    $codes[$mode] = $tr['status'] . ':' . $tr['detail'] . '/' . $er['status'];
}
ok(array_values(array_unique(array_map(fn ($m, $v) => $v === 'skipped:' . $m . '/sent' ? 'ok' : $v, array_keys($codes), $codes))) === ['ok'], 'every refusal: the text skipped with its code, the email sent (' . json_encode($codes) . ')');
ok(last_text_refusal(pdo(), 28) === 'no_sender', 'the last refusal is what the prefs tab will show');
sms_mode('server_error');
$t5 = $mk('SMOKE text 5xx');
act($marco, '/tickets/assign.php', ['ticket' => $t5, 'assignee' => 28]);
send_batch();
$tr = array_values(array_filter(outbox_rows($t5), fn ($o) => $o['channel'] === 'text'))[0];
ok($tr['status'] === 'queued' && (int) $tr['attempts'] === 1 && str_starts_with((string) $tr['detail'], 'retry:') && strtotime($tr['send_after']) > time() + 30, 'a 5xx: retry in a minute, attempts 1');
for ($i = 0; $i < 4; $i++) { q('UPDATE notification_outbox SET send_after = now() WHERE id = :id', ['id' => (int) $tr['id']]); send_batch(); }
$tr = q('SELECT * FROM notification_outbox WHERE id = :id', ['id' => (int) $tr['id']])[0];
ok($tr['status'] === 'failed' && (int) $tr['attempts'] === 5, 'the fifth failure: failed');
sms_mode('ok');
echo "3. No API key, the dedupe key, nobody\n";
$key = getenv('MALUMAIL_API_KEY');
putenv('MALUMAIL_API_KEY=');
$t6 = $mk('SMOKE no key');
act($marco, '/tickets/assign.php', ['ticket' => $t6, 'assignee' => 28]);
$r = send_batch();
$rows = outbox_rows($t6);
$er = array_values(array_filter($rows, fn ($o) => $o['channel'] === 'email'))[0]; $tr = array_values(array_filter($rows, fn ($o) => $o['channel'] === 'text'))[0];
ok($er['status'] === 'queued' && (int) $er['attempts'] === 0 && $er['detail'] === 'unconfigured' && $tr['status'] === 'sent', 'no API key: the email stays queued (unconfigured, attempts 0) and the text still goes');
putenv('MALUMAIL_API_KEY=' . $key);
send_batch();
ok(q('SELECT status FROM notification_outbox WHERE id = :id', ['id' => (int) $er['id']])[0]['status'] === 'sent', 'with the key back: sent');
$n = count(outbox_rows($t6));
notify_member(pdo(), 28, 'assigned', $t6, 'again', 'again', 'assigned:' . $t6 . ':28:' . 'evt1');
notify_member(pdo(), 28, 'assigned', $t6, 'again', 'again', 'assigned:' . $t6 . ':28:' . 'evt1');
ok(count(outbox_rows($t6)) === $n + 2, 'the same dedupe key twice queues once per channel (2 rows, not 4)');
q("UPDATE members SET status = 'inactive' WHERE id = 29");
ok(notify_member(pdo(), 29, 'assigned', $t6, 'x', 'x', 'assigned:' . $t6 . ':29:evt') === 0 && (int) one('SELECT count(*) FROM notification_outbox WHERE member_id = 29') === 0, 'an inactive member: nothing queued');
q("UPDATE members SET status = 'active' WHERE id = 29");
$GLOBALS['__run_facts'] = ['is_eval' => true];
ok(notify_member(pdo(), 28, 'assigned', $t6, 'x', 'x', 'assigned:' . $t6 . ':28:eval') === 0 && notify_requester(pdo(), $W['jo'], 'replied', $t6, 'x', 'x', 'replied:eval') === 0, 'an evaluation run: nothing queued');
unset($GLOBALS['__run_facts']);
echo "4. A rejected and a flaky address\n";
$tr1 = (int) act($marco, '/tickets/save.php', ['subject' => 'SMOKE rejected', 'body' => 'x', 'queue' => $W['it'], 'requester' => 'rejected@customer.invalid'])[1]['record_id'];
send_batch();
$er = array_values(array_filter(outbox_rows($tr1), fn ($o) => $o['kind'] === 'created'))[0];
ok($er['status'] === 'skipped' && str_starts_with((string) $er['detail'], 'undeliverable') && (string) one("SELECT status FROM outbound_email WHERE ticket_id = :t ORDER BY id DESC LIMIT 1", ['t' => $tr1]) === 'suppressed', 'a rejected address: skipped undeliverable, the outbound row suppressed');
$tf = (int) act($marco, '/tickets/save.php', ['subject' => 'SMOKE flaky', 'body' => 'x', 'queue' => $W['it'], 'requester' => 'flaky@customer.invalid'])[1]['record_id'];
send_batch();
$er = array_values(array_filter(outbox_rows($tf), fn ($o) => $o['kind'] === 'created'))[0];
ok($er['status'] === 'queued' && (int) $er['attempts'] === 1 && str_starts_with((string) $er['detail'], 'retry:502'), 'a 502 from MaluMail: retry');
finish();
