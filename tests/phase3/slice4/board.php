<?php
/** Proof — the board shows only what the view's audience may see (spec "Proof", 3): Marco's team board holds IT's tickets and none of Facilities'; closed never; solved by solved_days; columns, WIP, swimlanes, a list view as a board, a status off the board. */
require __DIR__ . '/lib.php';
$W = world();
$marco = as_member(27); $lena = as_member(28); $priya = as_member(26); $owner = as_member(1);
echo "1. Marco's team board\n";
[$c, $d] = board($marco);
$cols = columns_of($d);
ok($c === 200 && $d['view']['system_key'] === 'team_board' && array_keys($cols) === ['new', 'open', 'pending', 'on_hold', 'solved'], 'the default board: team_board with the five status columns in order (' . implode(',', array_keys($cols)) . ')');
$all = array_merge(...array_values($cols));
ok(in_array($W['t_jo'], $all, true) && in_array($W['t_jo2'], $all, true) && !in_array($W['t_fac'], $all, true) && !in_array($W['t_p1'], $all, true), 'IT\'s tickets are on it, none of Facilities\' or the general queue\'s');
ok(in_array($W['t_jo2'], $cols['open'], true), 'the open ticket sits in Open');
ok(page($priya, '/board')['code'] === 403, 'Priya: 403');
echo "2. Closed never; solved by solved_days\n";
$closed = (int) act($marco, '/tickets/save.php', ['subject' => 'SMOKE board closed', 'body' => 'x', 'queue' => $W['it']])[1]['record_id'];
act($marco, '/tickets/transition.php', ['ticket' => $closed, 'status' => 'open']);
act($lena, '/tickets/close.php', ['ticket' => $closed, 'resolution_code' => 'resolved']);
$old = (int) act($marco, '/tickets/save.php', ['subject' => 'SMOKE board solved long ago', 'body' => 'x', 'queue' => $W['it']])[1]['record_id'];
act($marco, '/tickets/transition.php', ['ticket' => $old, 'status' => 'solved', 'resolution_code' => 'resolved', 'note' => 'SMOKE done']);
q("UPDATE tickets SET solved_at = now() - interval '5 days' WHERE id = :t", ['t' => $old]);
$fresh = (int) act($marco, '/tickets/save.php', ['subject' => 'SMOKE board solved today', 'body' => 'x', 'queue' => $W['it']])[1]['record_id'];
act($marco, '/tickets/transition.php', ['ticket' => $fresh, 'status' => 'solved', 'resolution_code' => 'resolved', 'note' => 'SMOKE done']);
[$c, $d] = board($marco);
$cols = columns_of($d);
ok(column_of($d, $closed) === null, 'the closed ticket is on no column');
ok(in_array($fresh, $cols['solved'], true) && !in_array($old, $cols['solved'], true), 'solved today shows; solved 5 days ago is absent with solved_days = 3');
[$c, $b] = act($lena, '/views/save.php', ['name' => 'SMOKE week board', 'scope' => 'personal', 'layout' => 'board', 'filters' => json_encode(['queue_id' => [$W['it']]]), 'board' => json_encode(['column_field' => 'status', 'solved_days' => 7, 'wip' => ['open' => 1]])]);
$wk = (int) $b['record_id'];
[$c, $d] = board($lena, 'view=' . $wk);
$cols = columns_of($d);
ok($c === 200 && in_array($old, $cols['solved'], true), 'with solved_days = 7 it is present');
$open = array_values(array_filter($d['board']['columns'], fn ($x) => $x['key'] === 'open'))[0];
ok($open['wip'] === 1 && $open['count'] >= 1, 'the WIP limit of Open is carried (count ' . $open['count'] . ' / 1)');
$body = page($lena, '/board?view=' . $wk)['body'];
ok(preg_match('#id="board-column-open-count"[^>]*>\s*' . $open['count'] . ' / 1<#', $body) === 1 && ($open['count'] > 1 ? str_contains($body, 'board-wip-over') : true), 'the column header reads "count / limit"' . ($open['count'] > 1 ? ' in red' : ''));
echo "3. Swimlanes, other fields, a list view as a board\n";
[$c, $d] = board($lena, 'view=' . $wk . '&swimlane=priority');
ok($c === 200 && is_array($d['board']['lanes']) && count($d['board']['lanes']) >= 1 && isset($d['board']['lanes'][0]['columns']), 'swimlanes by priority: lanes each with columns');
$body = page($lena, '/board?view=' . $wk . '&swimlane=priority')['body'];
ok(preg_match_all('/id="board-lane-[a-z]+"/', $body) >= 1 && str_contains($body, 'id="board-column-normal-open"'), 'the page renders lane blocks with lane-scoped column ids');
[$c, $b] = act($lena, '/views/save.php', ['name' => 'SMOKE by assignee', 'scope' => 'personal', 'layout' => 'board', 'filters' => json_encode(['queue_id' => [$W['it']]]), 'board' => json_encode(['column_field' => 'assignee'])]);
[$c, $d] = board($lena, 'view=' . (int) $b['record_id']);
$cols = columns_of($d);
ok($c === 200 && isset($cols['none']) && in_array($closed, $cols['none'], true), 'columns by assignee: Unassigned first; the closed ticket shows here (closed is only hidden on a status board)');
[$c, $d] = board($lena, 'view=triage');
ok($c === 200 && $d['view']['system_key'] === 'triage' && array_keys(columns_of($d)) === ['new', 'open', 'pending', 'on_hold', 'solved'] && !in_array($W['t_jo2'], array_merge(...array_values(columns_of($d))), true), 'a list view opened on /board: status columns, its filters (Triage holds only new)');
echo "4. A status off the board\n";
$sid = (int) one("SELECT id FROM ticket_statuses WHERE key = 'on_hold'");
act($owner, '/settings/statuses/save.php', ['status' => $sid, 'label' => 'On hold', 'on_board' => 'no']);
[$c, $d] = board($marco);
ok(!isset(columns_of($d)['on_hold']), 'On hold taken off the board: no column');
act($owner, '/settings/statuses/save.php', ['status' => $sid, 'label' => 'On hold', 'on_board' => 'yes']);
[$c, $d] = board($marco, 'assignee=none&priority=urgent,high&q=SMOKE');
$pr = $d['filters']['priority'] ?? []; sort($pr);
ok($c === 200 && ($d['filters']['assignee'] ?? '') === 'none' && $pr === ['high', 'urgent'], 'the header filters ride on the view through the translator');
ok(count(array_filter(array_merge(...array_values(columns_of($d))), fn ($id) => (string) one('SELECT priority FROM tickets WHERE id = :t', ['t' => $id]) === 'normal')) === 0, 'and narrow the cards');
$last = q("SELECT after FROM activity_log WHERE action = 'screen.view' AND screen = 'board' ORDER BY id DESC LIMIT 1")[0] ?? null;
ok($last !== null && isset(json_decode($last['after'], true)['view_id']), 'the board\'s screen.view carries after.view_id');
finish();
