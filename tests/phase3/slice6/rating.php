<?php
/** Proof — rating (spec "Proof", 4): the scale follows csat_settings; a bad score demands no reason but offers the list; written once (a second says already received); the survey mail's ?r= token works once and not after expires_at; rating.submit logged; the assignee's rated notice; survey_send refusals. */
require __DIR__ . '/lib.php';
$W = world();
marco_in_general();
$marco = as_member(27); $lena = as_member(28);
$v = visitor();
[$c, $b, $num] = file_request($v, 'rater@customer.invalid', 'SMOKE to be rated');
$t = ticket_by_number($num); $token = mailed_token($t); $rid = (int) ticket_row($t)['requester_id'];
act($marco, '/tickets/assign.php', ['ticket' => $t, 'assignee' => 'me']);
echo "1. Not yet\n";
[$c, $b] = act($marco, '/ratings/send.php', ['ticket' => $t]);
ok($c === 422 && msg($b) === $num . ' is not solved yet.', 'survey_send on an unsolved ticket: 422 "' . $num . ' is not solved yet."');
ok(!str_contains(secure_page($v, $token)['body'], 'id="public-rate"'), 'no rating block on an open ticket');
act($marco, '/tickets/transition.php', ['ticket' => $t, 'status' => 'solved', 'resolution_code' => 'resolved']);
echo "2. The scale and a first view\n";
$body = secure_page($v, $token)['body'];
ok(str_contains($body, 'id="public-rate"') && str_contains($body, 'id="public-rate-good"') && str_contains($body, 'id="public-rate-bad"') && !str_contains($body, 'id="public-rate-3"') && str_contains($body, 'How did we do?'), 'good_bad: two buttons and the question');
$row = rating_row($t);
ok($row !== null && $row['score'] === null && (int) $row['requester_id'] === $rid && strlen($row['token_hash']) === 64 && $row['expires_at'] !== null, 'the rating row made on first view of the solved ticket (hash, expiry)');
ok(count(array_filter(q("SELECT option_value FROM (SELECT regexp_matches(:b, '<option value=\"([^\"]+)\"', 'g') AS m) x, LATERAL (SELECT m[1] AS option_value) y", ['b' => $body]), fn ($o) => $o['option_value'] === 'Took too long')) === 1, 'the bad-reason list is the configured one');
q("UPDATE csat_settings SET scale = 'five_point' WHERE id = 1");
$body = secure_page($v, $token)['body'];
ok(str_contains($body, 'id="public-rate-5"') && str_contains($body, 'id="public-rate-1"') && !str_contains($body, 'id="public-rate-good"'), 'five_point: five buttons');
q("UPDATE csat_settings SET scale = 'good_bad' WHERE id = 1");
echo "3. Rating once\n";
$since = last_activity_id();
[$c, $b, $h, $loc] = public_post($v, '/t/' . $token . '/rate', ['token' => $token, 'score' => '1', 'bad_reason' => 'Took too long', 'comment' => 'Three days for a cable.']);
$row = rating_row($t);
ok($c === 302 && $loc === '/t/' . $token . '?notice=rated' && (int) $row['score'] === 1 && $row['bad_reason'] === 'Took too long' && $row['comment'] === 'Three days for a cable.' && $row['responded_at'] !== null, 'a bad rating with a reason and a comment, written');
$l = array_values(array_filter(activity('rating.submit', $since), fn ($r) => (int) $r['ticket_id'] === $t));
ok(count($l) === 1 && (int) $l[0]['actor_requester_id'] === $rid && json_decode($l[0]['after'], true)['score'] === 1 && json_decode($l[0]['after'], true)['bad_reason'] === 'Took too long', 'rating.submit logged with the score and the reason');
$bell = q("SELECT * FROM notifications WHERE member_id = 27 AND ticket_id = :t AND kind = 'rated'", ['t' => $t]);
ok(count($bell) === 1 && str_contains($bell[0]['body'], 'Bad'), 'the assignee\'s rated notice (the bell; mail follows their preferences)');
[$c, $b, $h, $loc] = public_post($v, '/t/' . $token . '/rate', ['token' => $token, 'score' => '5']);
ok($c === 302 && $loc === '/t/' . $token . '?notice=already' && (int) rating_row($t)['score'] === 1, 'a second POST: already received; the row unchanged');
ok(str_contains(secure_page($v, $token)['body'], 'id="public-rate-done"'), 'the page says thank you — already received');
echo "4. The survey mail's token\n";
$v2 = visitor();
[$c, $b, $num2] = file_request($v2, 'rater2@customer.invalid', 'SMOKE surveyed by mail');
$t2 = ticket_by_number($num2); $tok2 = mailed_token($t2);
act($marco, '/tickets/transition.php', ['ticket' => $t2, 'status' => 'open']);
act($marco, '/tickets/transition.php', ['ticket' => $t2, 'status' => 'solved', 'resolution_code' => 'resolved']);
$since = last_activity_id();
[$c, $b] = act($marco, '/ratings/send.php', ['ticket' => $t2]);
ok($c === 200 && count(outbox($t2, 'survey')) === 1 && count(activity('survey.send', $since)) === 1, 'survey_send on a solved ticket: a survey notice queued, survey.send logged');
$mail = outbox($t2, 'survey')[0]['body'];
ok(preg_match('#/t/([a-f0-9]{48})/rate\?r=([a-f0-9]{48})#', $mail, $m) === 1, 'the mail carries /t/{secure}/rate?r={rating token}');
[$secure2, $r2] = [$m[1], $m[2]];
ok(hash('sha256', $r2) === rating_row($t2)['token_hash'] && $secure2 !== $tok2 && secure_page($v2, $tok2)['code'] === 200, 'the rating token is the row\'s; the survey link is a second live link — the created one still works');
[$c, $b] = act($marco, '/ratings/send.php', ['ticket' => $t2]);
ok($c === 422 && str_contains(msg($b), 'surveyed already'), 'surveying it again: 422');
$r = req('GET', '/t/' . $secure2 . '/rate?r=' . $r2, ['jar' => $v2]);
ok($r['code'] === 200 && str_contains($r['body'], 'id="public-rate-form"') && str_contains($r['body'], 'name="r" value="' . $r2 . '"'), 'the survey page by the mailed link shows the form carrying the rating token');
[$c, $b, $h, $loc] = public_post($v2, '/t/' . $secure2 . '/rate', ['token' => $secure2, 'r' => 'ffffffffffffffffffffffffffffffffffffffffffffffff', 'score' => '5']);
ok($c === 404 && rating_row($t2)['score'] === null, 'a wrong rating token: the dead-link page, nothing written');
q("UPDATE satisfaction_ratings SET expires_at = now() - interval '1 hour' WHERE ticket_id = :t", ['t' => $t2]);
[$c, $b, $h, $loc] = public_post($v2, '/t/' . $secure2 . '/rate', ['token' => $secure2, 'r' => $r2, 'score' => '5']);
ok($c === 404 && rating_row($t2)['score'] === null, 'after expires_at: the rating token is dead');
q("UPDATE satisfaction_ratings SET expires_at = now() + interval '1 day' WHERE ticket_id = :t", ['t' => $t2]);
[$c, $b, $h, $loc] = public_post($v2, '/t/' . $secure2 . '/rate', ['token' => $secure2, 'r' => $r2, 'score' => '5']);
ok($c === 302 && $loc === '/t/' . $secure2 . '?notice=rated' && (int) rating_row($t2)['score'] === 5, 'with the live token: rated Good');
[$c, $b, $h, $loc] = public_post($v2, '/t/' . $secure2 . '/rate', ['token' => $secure2, 'r' => $r2, 'score' => '1']);
ok($loc === '/t/' . $secure2 . '?notice=already', 'and once only');
file_put_contents(need('HD_DEV_STATE') . '/browser6.json', json_encode(['token' => $token, 'ticket' => $t]));
echo "5. An unsurveyed queue\n";
q("UPDATE csat_settings SET queue_ids = ARRAY[:q]::bigint[] WHERE id = 1", ['q' => $W['fac']]);
$t3 = (int) act($marco, '/tickets/save.php', ['subject' => 'SMOKE not surveyed', 'body' => 'x', 'queue' => $W['it'], 'requester' => $W['jo']])[1]['record_id'];
act($marco, '/tickets/transition.php', ['ticket' => $t3, 'status' => 'open']);
act($marco, '/tickets/transition.php', ['ticket' => $t3, 'status' => 'solved', 'resolution_code' => 'resolved']);
[$c, $b] = act($marco, '/ratings/send.php', ['ticket' => $t3]);
ok($c === 422 && msg($b) === 'That queue is not surveyed.', 'IT not among the surveyed queues: 422');
q("UPDATE csat_settings SET queue_ids = '{}' WHERE id = 1");
finish();
