<?php
/** Proof — settings (spec "Proof", 6): a changed delay changes the next survey's timing (send_due_surveys picks the ticket after the new delay, not before); csat_settings.save carries only the changed fields; nothing changed → no row; validation; the screen. */
require __DIR__ . '/lib.php';
$W = world();
$owner = as_member(1); $marco = as_member(27); $priya = as_member(26);
require_once dirname(__DIR__, 3) . '/app/features/tickets/handler.php';
echo "1. The screen and the save\n";
$body = page($owner, '/settings/csat')['body'];
ok(str_contains($body, 'id="csat-form"') && str_contains($body, 'id="csat-form-sentence"') && str_contains($body, 'goes 60 minutes after') && str_contains($body, 'id="csat-form-field-queues-' . $W['it'] . '"'), 'the settings screen with the live sentence and the queues');
ok(page($marco, '/settings/csat')['code'] === 403 && page($priya, '/settings/csat')['code'] === 403, 'support and a requester: 403');
$since = last_activity_id();
[$c, $b] = act($owner, '/settings/csat.php', ['enabled' => 'yes', 'scale' => 'good_bad', 'question' => 'How did we do?', 'send_delay_minutes' => 60, 'response_window_days' => 14, 'bad_reasons' => "Took too long\nNot resolved\nUnhelpful answer\nOther", 'queues' => ['']]);
ok($c === 200 && ($b['did'] ?? '') === 'Nothing changed' && count(activity('csat_settings.save', $since)) === 0, 'the same values: "Nothing changed", no row');
[$c, $b] = act($owner, '/settings/csat.php', ['send_delay_minutes' => 5, 'question' => 'Was this helpful?']);
$l = activity('csat_settings.save', $since);
ok($c === 200 && count($l) === 1 && array_keys(json_decode($l[0]['after'], true)) === ['question', 'send_delay_minutes'] && json_decode($l[0]['before'], true)['send_delay_minutes'] === 60, 'a change: csat_settings.save carries only the changed fields');
[$c, $b] = act($owner, '/settings/csat.php', ['send_delay_minutes' => 99999]);
ok($c === 422 && isset(fields($b)['send_delay_minutes']), 'a delay out of range: 422');
[$c, $b] = act($owner, '/settings/csat.php', ['scale' => 'stars']);
ok($c === 422 && isset(fields($b)['scale']), 'an unknown scale: 422');
[$c, $b] = act($owner, '/settings/csat.php', ['queues' => [$W['it']]]);
ok($c === 200 && pg_int_array((string) one('SELECT queue_ids FROM csat_settings')) === [$W['it']], 'queues chosen: IT only');
[$c, $b] = act($owner, '/settings/csat.php', ['queues' => ['']]);
ok($c === 200 && pg_int_array((string) one('SELECT queue_ids FROM csat_settings')) === [], 'none ticked: every queue');
echo "2. The delay drives the worker's call\n";
$t = (int) act($marco, '/tickets/save.php', ['subject' => 'SMOKE due survey', 'body' => 'x', 'queue' => $W['it'], 'requester' => $W['jo']])[1]['record_id'];
act($marco, '/tickets/transition.php', ['ticket' => $t, 'status' => 'open']);
act($marco, '/tickets/transition.php', ['ticket' => $t, 'status' => 'solved', 'resolution_code' => 'resolved']);
q("UPDATE tickets SET solved_at = now() - interval '3 minutes' WHERE id = :t", ['t' => $t]);
$pdo = pdo();
$pdo->exec("SELECT set_config('app.member_id', '1', false)");
$n = send_due_surveys($pdo);
ok(rating_row($t) === null, 'solved 3 minutes ago with a 5-minute delay: not surveyed yet (' . $n . ' sent)');
act($owner, '/settings/csat.php', ['send_delay_minutes' => 2]);
$n = send_due_surveys($pdo);
ok($n >= 1 && rating_row($t) !== null && count(outbox($t, 'survey')) === 1 && count(array_filter(q("SELECT * FROM activity_log WHERE action = 'survey.send' AND ticket_id = :t", ['t' => $t]), fn ($r) => $r['source'] === 'cron')) === 1, 'with a 2-minute delay: surveyed by send_due_surveys, logged with source cron');
ok(send_due_surveys($pdo) === 0, 'a second run sends nothing more');
act($owner, '/settings/csat.php', ['enabled' => 'no']);
$t2 = (int) act($marco, '/tickets/save.php', ['subject' => 'SMOKE survey off', 'body' => 'x', 'queue' => $W['it'], 'requester' => $W['jo']])[1]['record_id'];
act($marco, '/tickets/transition.php', ['ticket' => $t2, 'status' => 'open']);
act($marco, '/tickets/transition.php', ['ticket' => $t2, 'status' => 'solved', 'resolution_code' => 'resolved']);
q("UPDATE tickets SET solved_at = now() - interval '1 day' WHERE id = :t", ['t' => $t2]);
ok(send_due_surveys($pdo) === 0 && rating_row($t2) === null, 'with the survey off: nothing sent');
act($owner, '/settings/csat.php', ['enabled' => 'yes', 'send_delay_minutes' => 60, 'question' => 'How did we do?']);
finish();
