<?php
/** Proof — JSON mode (spec "Proof", 7): every handler and screen under an action token answers JSON; article_update keeps what it was not sent; the registry check. */
require __DIR__ . '/lib.php';
$W = world();
$owner = ['X-Action-Token: ' . person_token(1)];
$marco = ['X-Action-Token: ' . person_token(27)];
echo "1. Handlers\n";
[$c, $b] = act_token('/kb/admin/section.php', ['name' => 'SMOKE JSON section', 'visibility' => 'public'], $owner);
$sec = (int) ($b['record_id'] ?? 0);
ok($c === 200 && ($b['ok'] ?? false) === true && $sec > 0, 'section_save: {ok, record_id}');
[$c, $b] = act_token('/kb/admin/save.php', ['title' => 'SMOKE JSON article', 'body' => "# Hi\n\nSMOKE json body", 'section' => $sec, 'visibility' => 'public', 'tags' => 'a, b', 'status' => 'published'], $owner);
$aid = (int) ($b['record_id'] ?? 0);
ok($c === 200 && $aid > 0 && ($b['slug'] ?? '') === 'smoke-json-article' && ($b['location'] ?? '') === '/kb/admin/' . $aid . '/edit?notice=saved' && ($b['url'] ?? '') === '/kb/smoke-json-article', 'article_create: {ok, record_id, slug, location, url}');
[$c, $b] = act_token('/kb/admin/save.php', ['article' => $aid, 'tags' => 'c'], $owner);
$row = article_row($aid);
ok($c === 200 && $row['body_text'] === "# Hi\n\nSMOKE json body" && pg_text_array($row['tags']) === ['c'] && (int) $row['section_id'] === $sec && $row['visibility'] === 'public', 'article_update keeps what it was not sent');
[$c, $b] = act_token('/kb/admin/save.php', ['title' => str_repeat('x', 201), 'body' => 'y'], $owner);
ok($c === 422 && ($b['error']['code'] ?? '') === 'invalid' && isset(fields($b)['title']), 'validation: 422 invalid, by field');
[$c, $b] = act_token('/kb/admin/publish.php', ['article' => $aid, 'published' => 'no'], $owner);
ok($c === 200 && ($b['published'] ?? null) === false, 'article_publish: {ok, published}');
[$c, $b] = act_token('/kb/admin/publish.php', ['article' => $aid], $owner);
ok($c === 200 && ($b['published'] ?? null) === true, 'published left out means yes');
[$c, $b] = act_token('/kb/admin/link.php', ['ticket' => $W['t_jo'], 'article' => $aid], $marco);
ok($c === 200 && ($b['article_id'] ?? 0) === $aid && ($b['ticket_id'] ?? 0) === $W['t_jo'], 'article_suggest: {ok, article_id, ticket_id}');
[$c, $b] = act_token('/kb/admin/send.php', ['ticket' => $W['t_jo'], 'article' => $aid], $marco);
ok($c === 200 && ($b['message_id'] ?? 0) > 0 && ($b['record_id'] ?? 0) === $W['t_jo'] && ($b['article_id'] ?? 0) === $aid, 'article_send: {ok, message_id, article_id, record_id = the ticket, as ticket_reply answers}');
ok(act_token('/kb/admin/save.php', ['title' => 'x', 'body' => 'y'], $marco)[0] === 403, 'support → 403');
[$c, $b] = act_token('/kb/admin/archive.php', ['article' => $aid], $owner);
ok($c === 200 && ($b['did'] ?? '') === 'Archived SMOKE JSON article', 'article_archive: {ok, did}');
[$aid2] = mk_article(as_member(1), 'SMOKE JSON delete me', ['status' => 'draft']);
[$c, $b] = act_token('/kb/admin/delete.php', ['article' => $aid2], $owner);
ok($c === 200 && ($b['ok'] ?? false) === true && article_row($aid2) === [], 'article_delete: {ok}');
[$c, $b] = act_token('/kb/admin/section-archive.php', ['section' => $sec], $owner);
ok($c === 200 && ($b['ok'] ?? false) === true, 'section_archive: {ok}');
echo "2. Screens\n";
[$pub, $pubSlug] = mk_article(as_member(1), 'SMOKE JSON readable', ['body' => 'SMOKE readable body']);
$secSlug = q('SELECT slug FROM kb_sections WHERE archived_at IS NULL ORDER BY id LIMIT 1')[0]['slug'] ?? '';
[$c, $d] = screen(as_member(1), '/kb/?q=readable');
ok($c === 200 && is_array($d['sections']) && count($d['results']) >= 1 && $d['results'][0]['url'] === '/kb/' . $pubSlug && ($d['may']['edit'] ?? false) === true, 'kb-home answers JSON (sections, results, may.edit)');
[$c, $d] = screen(as_member(1), '/kb/' . $pubSlug);
ok($c === 200 && ($d['article']['article_id'] ?? 0) === $pub && isset($d['article']['body_html']) && is_array($d['attachments']), 'kb-article answers JSON with the body');
[$c, $d] = screen(as_member(1), '/kb/admin/?status=published');
ok($c === 200 && $d['status'] === 'published' && is_array($d['articles']) && is_array($d['sections']), 'kb-admin answers JSON');
[$c, $d] = screen(as_member(1), '/kb/admin/' . $pub . '/edit');
ok($c === 200 && ($d['article']['article_id'] ?? 0) === $pub && isset($d['visibilities']['public']), 'article-edit answers JSON');
[$c, $d] = screen(as_member(1), '/kb/admin/new?from_ticket=' . $W['t_jo']);
ok($c === 200 && $d['article'] === null && $d['start']['title'] === 'SMOKE Printer on fire' && $d['start']['from_ticket'] === $W['t_jo'], 'article-add with from_ticket answers the prefilled start');
if ($secSlug !== '') { [$c, $d] = screen(as_member(1), '/kb/s/' . $secSlug); ok($c === 200 && isset($d['section']['section_id']), 'kb-section answers JSON'); }
[$c, $d] = screen(as_member(1), '/tickets/' . $W['t_jo']);
ok($c === 200 && is_array($d['articles']) && count(array_filter($d['articles'], fn ($l) => $l['kind'] === 'sent' && $l['article_id'] === $aid)) === 1, "ticket-view's JSON carries the linked articles (the archived one still, to an editor)");
exit($GLOBALS['fails'] === 0 ? 0 : 1);
