// Headless Chromium proof of slice 9 (docs/build-specs/knowledge-base.md, "Proof", 7): a visitor's article page at 375 (the code block scrolls inside, the page never sideways), the home, the editors' desk, the form's Preview tab and the ticket's article picker at 375 and 1280.
import { createRequire } from 'node:module';
import crypto from 'node:crypto';
import fs from 'node:fs';
const require = createRequire('/var/www/web/node_modules/');
const { chromium } = require('playwright');
const BASE = 'http://127.0.0.1:8291';
const SHOTS = process.env.SHOTS || '/tmp/helpdesk-shots-p3s9';
const KEY = process.env.ACTION_TOKEN_KEY;
const fixture = JSON.parse(fs.readFileSync(new URL('../../../bin/dev_directory.json', import.meta.url), 'utf8'));
const mint = (member) => {
  const payload = `${member}.${Math.floor(Date.now() / 1000) + 60}.helpdesk.${crypto.randomBytes(16).toString('hex')}`;
  const token = payload + '.' + crypto.createHmac('sha256', KEY).update('sso:' + payload).digest('hex');
  const text = Buffer.from(JSON.stringify({ ...fixture.claims[String(member)], member_id: member })).toString('base64url');
  return BASE + '/sso?' + new URLSearchParams({ token, claims: text + '.' + crypto.createHmac('sha256', KEY).update(text).digest('hex') });
};
let failed = 0, passed = 0;
const ok = (c, l) => { if (c) passed++; else failed++; console.log((c ? '  ok   ' : '  FAIL ') + l); };
const browser = await chromium.launch();
const widthOK = async (page, label, vw) => { const o = await page.evaluate(() => ({ sw: document.documentElement.scrollWidth, iw: window.innerWidth })); ok(o.sw === o.iw && o.iw === vw, `no sideways scroll on ${label} (scrollWidth ${o.sw} = ${o.iw})`); };
const slug = process.env.KB_SLUG || 'smoke-browser-article';
const ticket = process.env.KB_TICKET || '1';
for (const [name, vp] of [['375 x 740', { width: 375, height: 740 }], ['1280 x 800', { width: 1280, height: 800 }]]) {
  const ctx = await browser.newContext({ viewport: vp, deviceScaleFactor: 2, isMobile: vp.width < 600, hasTouch: vp.width < 600 });
  const page = await ctx.newPage();
  const errors = [];
  page.on('console', (m) => { if (m.type() === 'error' && !/status of (422|403|404)|sendAbort|^htmx:afterRequest$/.test(m.text())) errors.push(m.text()); });
  page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
  console.log(name + ' — a visitor');
  await page.goto(BASE + '/kb/' + slug, { waitUntil: 'networkidle' });
  ok(await page.locator('#article-body').count() === 1 && await page.locator('#nav-kb').count() === 0, 'the public article renders bare');
  const pre = await page.locator('#article-body pre').first().evaluate((el) => ({ sw: el.scrollWidth, cw: el.clientWidth, ov: getComputedStyle(el).overflowX }));
  ok(pre.sw > pre.cw && pre.ov === 'auto', `the long code line scrolls inside its block (${pre.sw} > ${pre.cw})`);
  await widthOK(page, "a visitor's article", vp.width);
  await page.screenshot({ path: `${SHOTS}/${vp.width}-article.png`, fullPage: false });
  await page.goto(BASE + '/kb/', { waitUntil: 'networkidle' });
  ok(await page.locator('#kb-search').count() === 1 && await page.locator('[id^="kb-section-card-"]').count() >= 1, 'the public home: the search and the sections');
  await page.locator('#kb-search').pressSequentially('zebra', { delay: 20 });
  await page.keyboard.press('Enter');
  await page.waitForURL(/\/kb\/\?q=zebra/, { timeout: 5000 });
  await page.waitForSelector('#kb-results-list', { timeout: 5000 });
  ok(await page.locator('[id^="article-row-"]').count() >= 1, "a visitor's search is a plain form (no HTMX on the bare layout): Enter lists the match");
  await widthOK(page, 'the public home', vp.width);
  console.log(name + ' — the owner');
  await page.goto(mint(1), { waitUntil: 'networkidle' });
  await page.goto(BASE + '/kb/', { waitUntil: 'networkidle' });
  await page.locator('#kb-search').pressSequentially('zebra', { delay: 20 });
  await page.waitForSelector('#kb-results-list', { timeout: 5000 });
  ok(await page.locator('[id^="article-row-"]').count() >= 1 && page.url().includes('q=zebra'), 'in the shell, typing searches as you type (HTMX) and pushes ?q=');
  await page.goto(BASE + '/kb/admin/', { waitUntil: 'networkidle' });
  ok(await page.locator('#kb-admin-table').count() === 1 && await page.locator('#kb-admin-sections').count() === 1, "the editors' desk: the table and the sections");
  await widthOK(page, 'the desk', vp.width);
  await page.goto(BASE + '/kb/admin/new', { waitUntil: 'networkidle' });
  await page.fill('#article-form-field-body', '# Preview me\n\nSome **bold** words.');
  await page.click('#article-form-tab-preview');
  await page.waitForSelector('#article-preview strong', { timeout: 5000 });
  ok((await page.locator('#article-preview').innerText()).includes('Preview me') && await page.locator('#article-form-write').isHidden(), 'the Preview tab renders the Markdown in place');
  await widthOK(page, 'the article form', vp.width);
  await page.screenshot({ path: `${SHOTS}/${vp.width}-article-form.png`, fullPage: false });
  await page.goto(BASE + '/tickets/' + ticket, { waitUntil: 'networkidle' });
  await page.click('#ticket-reply-article-btn');
  await page.waitForSelector('#article-picker-card', { timeout: 5000 });
  ok(await page.locator('[id^="article-pick-"][id$="-send"]').count() >= 1, 'the composer opens the article picker with Send');
  await widthOK(page, 'the ticket with the picker', vp.width);
  ok(errors.length === 0, 'no console errors' + (errors.length ? ': ' + errors.join(' / ') : ''));
  await ctx.close();
}
await browser.close();
console.log(`${passed} passed, ${failed} failed`);
process.exit(failed ? 1 : 0);
